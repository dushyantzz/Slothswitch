"""Mock task model adapter for testing the full pipeline without API keys.

Returns canned responses based on the route and request content.
"""

from __future__ import annotations

import time
from typing import Any

from slothswitch.adapters import TaskModelAdapter
from slothswitch.schemas import RouteCategory, RoutingRequest, TaskResult


class MockTaskModelAdapter(TaskModelAdapter):
    """Simulates task execution with deterministic canned responses.

    Useful for:
    - End-to-end pipeline testing
    - Demo mode without API keys
    - Evaluation harness dry runs
    """

    def __init__(self, model_name: str = "mock-model", latency_ms: float = 50.0) -> None:
        self._model_name = model_name
        self._simulated_latency_ms = latency_ms

    @property
    def name(self) -> str:
        return self._model_name

    def execute(
        self,
        request: RoutingRequest,
        route: RouteCategory,
        context: dict[str, Any] | None = None,
    ) -> TaskResult:
        """Return a canned response based on the route."""
        start = time.perf_counter()

        response_map: dict[RouteCategory, str] = {
            RouteCategory.FAST_PATH: self._fast_path_response(request),
            RouteCategory.SMALL_LLM: self._small_llm_response(request),
            RouteCategory.LARGE_LLM: self._large_llm_response(request),
            RouteCategory.CLARIFY: self._clarify_response(request),
            RouteCategory.FALLBACK: self._fallback_response(request),
            RouteCategory.HUMAN_REVIEW: self._human_review_response(request),
        }

        output = response_map.get(route, "Unable to process this request.")
        elapsed = (time.perf_counter() - start) * 1000 + self._simulated_latency_ms

        return TaskResult(
            request_id=request.request_id,
            route_used=route,
            output=output,
            success=True,
            model_used=self._model_name,
            latency_ms=elapsed,
            token_usage={"prompt_tokens": 50, "completion_tokens": 30, "total_tokens": 80},
            estimated_cost_usd=0.0,  # simulated — no real cost
        )

    # ---- Canned response generators ----

    @staticmethod
    def _fast_path_response(request: RoutingRequest) -> str:
        return (
            f"[FAST_PATH] Your request '{request.request_id}' has been processed "
            "using a deterministic handler. No LLM was needed."
        )

    @staticmethod
    def _small_llm_response(request: RoutingRequest) -> str:
        return (
            f"[SMALL_LLM] Thank you for your inquiry (#{request.request_id}). "
            "Based on your request, here is a helpful response generated by our "
            "efficient model. Please let us know if you need further assistance."
        )

    @staticmethod
    def _large_llm_response(request: RoutingRequest) -> str:
        return (
            f"[LARGE_LLM] Your complex request (#{request.request_id}) has been "
            "analyzed in depth. Here is a comprehensive response that addresses "
            "the multiple aspects of your query with detailed reasoning."
        )

    @staticmethod
    def _clarify_response(request: RoutingRequest) -> str:
        return (
            f"[CLARIFY] We need more information to help you with request "
            f"#{request.request_id}. Could you please provide additional details "
            "about your specific issue?"
        )

    @staticmethod
    def _fallback_response(request: RoutingRequest) -> str:
        return (
            f"[FALLBACK] Request #{request.request_id} could not be routed with "
            "sufficient confidence. It has been sent to our default handler. "
            "A support agent will follow up if needed."
        )

    @staticmethod
    def _human_review_response(request: RoutingRequest) -> str:
        return (
            f"[HUMAN_REVIEW] Request #{request.request_id} has been flagged for "
            "human review due to its sensitive nature. A qualified agent will "
            "review and respond within our SLA."
        )


